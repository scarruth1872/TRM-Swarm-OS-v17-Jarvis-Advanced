def spawn_microkernel_scenario(name, task_spec, function="instella_thinking_matrix"):
    """Spawn a microkernel subagent for a scenario."""
    payload = {
        "parent_role": "Architect",
        "subagent_name": name.replace(" ", "_")[:40],
        "task_spec": task_spec,
        "persona": "continuum",
        "continuum_function": function,
        "memory_limit_mb": 128,
        "ttl_seconds": 30
    }
    try:
        r = requests.post(f"{TRM}/swarm/microkernel/spawn-continuum", json=payload, timeout=15)
        if r.status_code == 200:
            data = r.json()
            sa = data.get("subagent", {})
            return {
                "id": sa.get("subagent_id", "?"),
                "status": data.get("status", "?"),
                "function": function
            }
        else:
            return {"error": f"HTTP {r.status_code}", "detail": r.text[:100]}
    except Exception as e:
        return {"error": str(e)}

