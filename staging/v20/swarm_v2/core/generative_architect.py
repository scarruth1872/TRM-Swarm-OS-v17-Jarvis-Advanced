class BlueprintProposal(BaseModel):
    """Architectural blueprint generated by Archi."""
    component: str
    proposed_code: str
    rationale: str
    dependencies: List[str] = []
    voltage_multiplier: float = 1.0
    k3_confidence: str = "+1"  # +1=TRUE, 0=UNKNOWN, -1=FALSE
    timestamp: str = Field(default_factory=lambda: datetime.now().isoformat())


class ArchitectStatus(BaseModel):
    """Live status of Generative Architect Studio."""
    mode: str = "Generative Architect Studio v13"
    hardware_bound: bool = False
    phi_v: float = 1.0
    total_blueprints: int = 0
