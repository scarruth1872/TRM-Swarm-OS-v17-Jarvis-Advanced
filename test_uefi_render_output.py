LCARS_ORANGE = (0xFF, 0x66, 0x00)

def save_bmp(filename, pixels, width, height):
    # BMP file format writer (zero external dependencies)
    row_size = (width * 3 + 3) & ~3
    image_size = row_size * height
    file_size = 54 + image_size

    header = struct.pack(
        '<2sIHHI',
        b'BM',
        file_size,
        0, 0,
        54
    )
    dib = struct.pack(
        '<IiiHHIIiiII',
        40,
        width, -height, # Top-down DIB
        1,
        24,
        0,
        image_size,
        2835, 2835,
        0, 0
    )

    with open(filename, 'wb') as f:
        f.write(header)
        f.write(dib)
        for y in range(height):
            row = bytearray()
            for x in range(width):
                r, g, b = pixels[y][x]
                row.extend([b, g, r]) # BGR order
            # Padding
            padding = (4 - (len(row) % 4)) % 4
            row.extend(b'\x00' * padding)
            f.write(row)

